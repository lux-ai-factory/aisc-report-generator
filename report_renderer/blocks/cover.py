"""The Cover block."""
from __future__ import annotations

import base64
from datetime import timezone

from aisc_report_plugin_interface import BaseBlockRenderer, BlockResult

from ..style import MARKING_LABELS


class CoverBlock(BaseBlockRenderer):
    type_id = "cover"
    title = "Cover"
    contract_version = 1
    description = "The first page: title, project, version, date and author."
    options_schema = {
        "type": "object",
        "additionalProperties": False,
        "properties": {
            "report_title": {"type": "string", "minLength": 1, "maxLength": 200, "title": "Report title",
                             "description": "The big title on the first page."},
            "subtitle": {"type": "string", "minLength": 0, "maxLength": 300, "title": "Subtitle",
                         "description": "A line under the title."},
            "show_logo": {"type": "boolean", "title": "Show the logo",
                          "description": "Prints the template's logo above the title.", "x-aisc-more": True},
            "show_generated_by": {"type": "boolean", "title": "Name the author",
                                  "description": "Prints who generated the document.", "x-aisc-more": True},
        },
    }
    default_options = {"report_title": "AI system assessment report", "subtitle": "", "show_logo": True, "show_generated_by": True}
    reads = ("platform",)
    choice_options = ()

    def load(self, ctx, options):
        return {"logo": ctx.data.logo}

    def render(self, data, options, ctx):
        """Never empty; shows a banner when newer versions exist."""
        logo = None
        if options["show_logo"] and data and data.get("logo"):
            mime, raw = data["logo"]
            logo = f"data:{mime};base64," + base64.b64encode(raw).decode("ascii")
        t = ctx.t
        banner = None
        if ctx.newer_versions:
            banner = t("This report covers version {number}. Version {newer} is newer.",
                       number=ctx.system["number"], newer=max(ctx.newer_versions))
        if getattr(getattr(ctx.report, "selection", None), "other_versions", False):
            # the report's selection includes runs of other versions
            note = t("Includes test runs made against other versions.")
            banner = f"{banner} {note}" if banner else note
        if ctx.mode in ("pdf", "docx"):
            generated_by = t("Generated by {name}", name=ctx.report.requested_by) if ctx.report.requested_by else None
        else:
            generated_by = t("Generated by: preview")
        marking = getattr(ctx.report, "marking", "none")
        marking_label = t(MARKING_LABELS[marking]) if marking in MARKING_LABELS else None
        html = self.render_package_template(
            "templates/cover.html.j2", options=options, project=ctx.project, system=ctx.system,
            generated=ctx.generated_at.astimezone(timezone.utc).strftime("%Y-%m-%d"), report=ctx.report,
            generated_by=generated_by if options["show_generated_by"] else None, banner=banner, logo=logo,
            marking=marking_label, t=t)
        return BlockResult(html=html, status="ok")
